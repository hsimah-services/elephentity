//! A small writer for C# source: indentation, braces, doc comments and a file header.
//!
//! Generated code is never formatted by a tool afterwards, so this is what makes it readable. It knows nothing about C#
//! beyond braces; what to write is the emitters' business.

use std::fmt::Write as _;

/// Lines of C#, indented by block.
#[derive(Default)]
pub struct Code {
    lines: Vec<String>,
    depth: usize,
}

impl Code {
    pub fn new() -> Self {
        Self::default()
    }

    /// One line at the current depth; an empty string is a blank line.
    pub fn line(&mut self, text: impl AsRef<str>) -> &mut Self {
        let text = text.as_ref();

        for part in text.split('\n') {
            if part.is_empty() {
                self.lines.push(String::new());
            } else {
                self.lines
                    .push(format!("{}{part}", "    ".repeat(self.depth)));
            }
        }

        self
    }

    pub fn blank(&mut self) -> &mut Self {
        self.line("")
    }

    /// `header` and an opening brace, then one level deeper.
    pub fn open(&mut self, header: impl AsRef<str>) -> &mut Self {
        self.line(header);
        self.line("{");
        self.depth += 1;

        self
    }

    /// A bare brace, for a block inside a `case`.
    pub fn block(&mut self) -> &mut Self {
        self.line("{");
        self.depth += 1;

        self
    }

    pub fn close(&mut self) -> &mut Self {
        self.depth -= 1;
        self.line("}")
    }

    /// A closing brace with a trailing semicolon, for object initialisers and `record` bodies.
    pub fn close_with(&mut self, suffix: &str) -> &mut Self {
        self.depth -= 1;
        self.line(format!("}}{suffix}"))
    }

    /// An XML documentation summary; a blank line in `text` starts a new paragraph.
    pub fn doc(&mut self, text: &str) -> &mut Self {
        // C# ends a line at more than \n: \r, U+0085, U+2028 and U+2029 do too, and text from a spec must not be able to
        // start a line of code. Every terminator becomes a \n first, so each gets its own `///`.
        let normalized = text
            .replace("\r\n", "\n")
            .replace(['\r', '\u{85}', '\u{2028}', '\u{2029}'], "\n");
        let escaped = escape_xml(normalized.trim());

        self.line("/// <summary>");

        for line in escaped.lines() {
            if line.trim().is_empty() {
                self.line("/// <para />");
            } else {
                self.line(format!("/// {}", line.trim_end()));
            }
        }

        self.line("/// </summary>")
    }

    pub fn finish(self) -> String {
        self.lines.join("\n")
    }
}

pub fn escape_xml(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

/// A complete source file: what the tools and the compiler need before the first type.
pub struct File {
    pub path: String,
    pub namespace: String,
    pub usings: Vec<String>,
    pub code: Code,
}

impl File {
    pub fn new(path: impl Into<String>, namespace: impl Into<String>) -> Self {
        Self {
            path: path.into(),
            namespace: namespace.into(),
            usings: Vec::new(),
            code: Code::new(),
        }
    }

    /// The body the orchestrator signs. It adds its own comment header above this.
    pub fn render(self) -> (String, String) {
        let mut body = String::new();

        // Marks the file as generated for the compiler's analyzers, whose style rules are for hand-written code.
        let _ = writeln!(body, "// <auto-generated/>");
        let _ = writeln!(body, "#nullable enable");
        let _ = writeln!(body, "#pragma warning disable CS1591");
        let _ = writeln!(body);
        let _ = writeln!(body, "namespace {};", self.namespace);
        let _ = writeln!(body);

        for using in &self.usings {
            let _ = writeln!(body, "using {using};");
        }

        if !self.usings.is_empty() {
            let _ = writeln!(body);
        }

        body.push_str(&self.code.finish());
        body.push('\n');

        (self.path, body)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_csharp_line_terminator_in_a_description_starts_a_new_doc_line() {
        for terminator in ["\n", "\r\n", "\r", "\u{85}", "\u{2028}", "\u{2029}"] {
            let mut code = Code::new();
            code.doc(&format!("Name.{terminator}public static class Evil {{}}"));
            let text = code.finish();

            for line in text.lines() {
                assert!(
                    line.starts_with("///"),
                    "{terminator:?} let `{line}` out of the comment"
                );
            }

            assert!(
                !text.contains(['\r', '\u{85}', '\u{2028}', '\u{2029}']),
                "{terminator:?}"
            );
        }
    }
}
