//! The C# side: `SqliteStorageManifest.cs`, a factory for the `SqliteStorageManifest` that `Elephentity.Sqlite` loads. It carries the
//! initial schema as well, which `SqliteInstaller` runs; PHP gets that as a separate `install.php`.

use crate::csharp::literal;
use crate::storage::{Column, Index, Model, Part, Table};

const NS: &str = "global::Elephentity.Sqlite.Manifest";
const RUNTIME: &str = "global::Elephentity.Runtime.Storage";
const MAP: &str = "global::System.Collections.Generic.Dictionary";

fn column(c: &Column) -> String {
    format!(
        "new({}, {}, {}, {}, {})",
        literal(&c.name),
        literal(&c.ty),
        c.nullable,
        c.identity,
        c.default.as_deref().map(literal).unwrap_or("null".into())
    )
}

fn index(i: &Index) -> String {
    format!(
        "new({}, [{}], {})",
        literal(&i.name),
        i.columns
            .iter()
            .map(|c| literal(c))
            .collect::<Vec<_>>()
            .join(", "),
        i.unique
    )
}

/// A table as the value of `["key"] = `, on a line indented by `pad` spaces.
fn table(t: &Table, pad: usize) -> String {
    let inner = " ".repeat(pad + 4);
    let list = |entries: Vec<String>| {
        if entries.is_empty() {
            "[]".to_owned()
        } else {
            format!(
                "[\n{}\n{inner}]",
                entries
                    .iter()
                    .map(|entry| format!("{inner}    {entry},"))
                    .collect::<Vec<_>>()
                    .join("\n")
            )
        }
    };
    format!(
        "new(\n{inner}{},\n{inner}{},\n{inner}{},\n{inner}{})",
        literal(&t.name),
        list(t.columns.iter().map(column).collect()),
        list(t.indexes.iter().map(index).collect()),
        literal(&t.primary)
    )
}

fn statement(parts: &[Part]) -> String {
    format!(
        "new([{}])",
        parts
            .iter()
            .map(|part| match part {
                Part::Sql(text) => format!("Sql({})", literal(text)),
                Part::Name(name) => format!("Name({})", literal(name)),
            })
            .collect::<Vec<_>>()
            .join(", ")
    )
}

pub fn render(model: &Model, namespace: &str) -> String {
    let mut out = String::new();

    out.push_str("// <auto-generated/>\n#nullable enable\n#pragma warning disable CS1591\n\n");
    out.push_str(&format!("namespace {namespace};\n\n"));
    out.push_str("/// <summary>\n/// How this project's entities are laid out in a SQLite database, and the statements that create it: the storage manifest <c>Elephentity.Sqlite</c> loads.\n/// Which database to use is configuration, not this file.\n/// </summary>\n");
    out.push_str("public static class SqliteStorageManifestFactory\n{\n");
    out.push_str(&format!(
        "    /// <summary>The manifest. Install it with <c>SqliteInstaller</c>, and give it to <c>SqliteAdaptor</c>.</summary>\n    public static {NS}.SqliteStorageManifest Create() =>\n        new(\n            new {MAP}<string, {NS}.SqliteTable>\n            {{\n"
    ));
    for e in &model.entities {
        out.push_str(&format!(
            "                [{}] = {},\n",
            literal(&e.name),
            table(&model.tables[&e.table], 16)
        ));
    }
    out.push_str("            },\n");

    out.push_str(&format!(
        "            new {MAP}<string, {NS}.SqliteEdgePlacement>\n            {{\n"
    ));
    for p in &model.placements {
        out.push_str(&format!(
            "                [{}] = new({}, {}, {}, {RUNTIME}.RelationKind.{}, {}, {}, {}, {}),\n",
            literal(&format!("{}.{}", p.entity, p.edge)),
            literal(&p.entity),
            literal(&p.edge),
            literal(&p.target),
            p.relation,
            literal(&p.table),
            literal(&p.local),
            p.remote.as_deref().map(literal).unwrap_or("null".into()),
            literal(&p.target_table)
        ));
    }
    out.push_str("            },\n");

    out.push_str(&format!(
        "            new {MAP}<string, global::System.Collections.Generic.IReadOnlyDictionary<string, string>>\n            {{\n"
    ));
    for e in &model.entities {
        out.push_str(&format!(
            "                [{}] = new {MAP}<string, string>\n                {{\n",
            literal(&e.name)
        ));
        for (field, stored) in &e.fields {
            out.push_str(&format!(
                "                    [{}] = {},\n",
                literal(field),
                literal(stored)
            ));
        }
        out.push_str("                },\n");
    }
    out.push_str("            },\n");

    out.push_str(&format!(
        "            new {MAP}<string, {NS}.SqliteTable>\n            {{\n"
    ));
    for name in &model.join_tables {
        out.push_str(&format!(
            "                [{}] = {},\n",
            literal(name),
            table(&model.tables[name], 16)
        ));
    }
    out.push_str("            },\n");

    out.push_str("            [\n");
    for parts in model.install() {
        out.push_str(&format!("                {},\n", statement(&parts)));
    }
    out.push_str("            ]);\n\n");

    out.push_str(&format!(
        "    private static {NS}.SqliteStatementPart Sql(string text) => {NS}.SqliteStatementPart.Sql(text);\n\n    private static {NS}.SqliteStatementPart Name(string name) => {NS}.SqliteStatementPart.Name(name);\n}}\n"
    ));

    out
}
