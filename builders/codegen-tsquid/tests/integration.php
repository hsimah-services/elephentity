<?php

declare(strict_types=1);

// Run in this workspace, or pass a directory containing the sibling repositories.
$workspace = $argv[1] ?? dirname(__DIR__, 2);
require $workspace . '/elephentity/vendor/autoload.php';
require $workspace . '/elephentity-graphql-php/vendor/autoload.php';
require __DIR__ . '/../src/Manifest.php';
require __DIR__ . '/../src/HtmlResponse.php';
require __DIR__ . '/../src/InitialData.php';

use Eleph\Tsquid\{InitialData, Manifest};
use GraphQL\GraphQL;
use GraphQL\Utils\BuildSchema;

function check(bool $condition, string $message): void
{
    if (!$condition) {
        throw new RuntimeException($message);
    }
}

function command(array $args): array
{
    $errorFile = tempnam(sys_get_temp_dir(), 'tsquid-stderr-');
    try {
        $process = proc_open($args, [0 => ['file', '/dev/null', 'r'], 1 => ['pipe', 'w'], 2 => ['file', $errorFile, 'w']], $pipes);
        $output = stream_get_contents($pipes[1]);
        fclose($pipes[1]);
        $status = proc_close($process);
        return [$status, $output . file_get_contents($errorFile)];
    } finally {
        unlink($errorFile);
    }
}

$project = sys_get_temp_dir() . '/tsquid-integration-' . bin2hex(random_bytes(6));
mkdir($project . '/spec/entities', recursive: true);
try {
    copy(__DIR__ . '/fixtures/starter.manifest.json', $project . '/routes.manifest.json');
    file_put_contents($project . '/spec/project.yml', "project: TsquidFixture\nstorage:\n  driver: sqlite\n  tablePrefix: fixture_\nintegrations:\n  tsquid:\n");
    file_put_contents($project . '/spec/entities/Book.yml', "entity: Book\nstorage:\n  table: book\nfields:\n  title:\n    type: string\n    required: true\n");
    file_put_contents($project . '/eleph.json', json_encode([
        'spec' => 'spec',
        'codegen' => $workspace . '/elephentity-codegen/bin/eleph-codegen',
        'targets' => [
            'sqlite' => ['builder' => $workspace . '/elephentity-codegen-sqlite/bin/eleph-gen-sqlite', 'output' => 'generated/sqlite', 'language' => 'php'],
            'tsquid' => ['builder' => dirname(__DIR__) . '/bin/eleph-gen-tsquid', 'output' => 'generated/tsquid', 'manifest' => '../../routes.manifest.json'],
        ],
    ], JSON_THROW_ON_ERROR));
    $generate = [getenv('ELEPH') ?: 'eleph', 'generate', '--project', $project];
    [$status, $output] = command($generate);
    check($status === 0, 'Real spec compiler/orchestrator generation failed: ' . $output);
    $path = $project . '/generated/tsquid/tsquid-manifest.php';
    check(str_contains(file_get_contents($path), 'GENERATED BY Elephentity'), 'Signed artifact');
    $manifest = Manifest::fromFile($path);
    [$status, $output] = command([...$generate, '--check']);
    check($status === 0, 'Clean generation drift check: ' . $output);

    $schema = BuildSchema::build('type Query { viewer: Viewer } type Viewer { id: ID!, name: String! }');
    $html = '<html><head></head><body><script type="module" src="/app.js"></script></body></html>';
    foreach (['Alice', 'Bob'] as $viewer) {
        $initial = new InitialData($manifest, static fn ($text, $variables, $operation) => GraphQL::executeQuery(
            $schema, $text, rootValue: ['viewer' => ['id' => $viewer, 'name' => $viewer]], variableValues: $variables, operationName: $operation,
        )->toArray());
        $response = $initial->render('/me', $html);
        check($response->headers === ['Cache-Control' => 'private, no-store'], 'Private response');
        preg_match('/id="tsquid-data">(.*?)<\/script>/s', $response->body, $payload);
        $data = json_decode($payload[1], flags: JSON_THROW_ON_ERROR);
        check($data->responses[0]->response->data->viewer->name === $viewer, 'Current viewer execution');
        check(!isset($data->responses[0]->response->errors), 'Exact starter query executes successfully');
        if ($viewer === 'Alice' && isset($argv[2])) {
            file_put_contents($argv[2], $payload[1]);
        }
    }
    $source = json_decode(file_get_contents($project . '/routes.manifest.json'), flags: JSON_THROW_ON_ERROR);
    $source->routes[1]->query->text .= "\n";
    file_put_contents($project . '/routes.manifest.json', json_encode($source, JSON_THROW_ON_ERROR));
    [$status] = command([...$generate, '--check']);
    check($status !== 0, 'Changed query must fail drift check');
    $before = file_get_contents($path);
    $source->version = 2;
    file_put_contents($project . '/routes.manifest.json', json_encode($source, JSON_THROW_ON_ERROR));
    [$status] = command($generate);
    check($status !== 0 && file_get_contents($path) === $before, 'Invalid manifest must not modify output');
    echo "Spec → describe → generate → signed PHP → viewer-scoped GraphQL → HTML passed; drift and atomic failure checks passed.\n";
} finally {
    $files = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($project, FilesystemIterator::SKIP_DOTS), RecursiveIteratorIterator::CHILD_FIRST);
    foreach ($files as $file) {
        $file->isDir() ? rmdir($file->getPathname()) : unlink($file->getPathname());
    }
    rmdir($project);
}
